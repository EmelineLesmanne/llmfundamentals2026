from pathlib import Path

from lab3_hybrid_search import fuse
from lab_tools import ask_rag, build_prompt, get_corpus, get_llm, hybrid_search
from loguru import logger

RULES = """TODO write the rules here"""

# Everything below only runs when you run this file directly (lab 5 imports RULES).
if __name__ == "__main__":
    if RULES.startswith("TODO"):
        raise SystemExit("TODO not done yet: write RULES")

    corpus = get_corpus()
    llm = get_llm()
    questions = [
        "From what date does the AI Act apply to the high-risk AI systems of Annex III?",
        "What does the Data Act say about access to data generated by connected products?",
    ]
    # What does the model really receive? The 5 best chunks (found by hybrid search) go in the prompt, after your rules.
    hits = hybrid_search(corpus, llm, questions[0], fuse, k=5)
    chunks = [corpus.by_id[chunk_id] for chunk_id, _ in hits]
    prompt_file = Path(__file__).parent / "prompt_sent.txt"
    prompt_file.write_text(build_prompt(questions[0], chunks, RULES), encoding="utf-8")
    logger.info("The prompt sent to the model (first question) is saved in prompt_sent.txt, next to this lab: open it.")

    received = ""  # what the model answers, for the file answer_received.txt
    for question in questions:
        logger.info(f"===== {question}")
        answer = ask_rag(llm, corpus, question, RULES, fuse, verbose=True)
        logger.info(f"citations: {answer.citations}")
        logger.info(f"answerable: {answer.answerable}")
        received += f"Question: {question}\n\nAnswer: {answer.answer}\n\n"
        received += f"Citations: {answer.citations}\nAnswerable: {answer.answerable}\n\n\n"
    (Path(__file__).parent / "answer_received.txt").write_text(received, encoding="utf-8")
    logger.info("The answers of the model are saved in answer_received.txt, next to this lab: open it.")

