"""
LAB 1 - The golden dataset, and your labels (about 20 minutes, no model call)

Goal: see what an evaluation starts from, and do by hand what a judge model will do later.

An evaluation needs a GOLDEN DATASET: questions for which we know what a good answer looks like. Each item has
    id, type, question,
    reference         what a good answer says,
    gold_articles     the articles that contain the answer (here we use articles, not chunks: the dataset stays valid if the
                      chunking changes),
    expected          "answer", or "refuse" when the corpus cannot answer.
Ours has 13 questions. They were written by hand: questions generated by a model from the chunks reuse the wording of the
chunk and make the search look better than it is.

The kit also gives you 13 real answers of the application (the RAG of the previous sessions), and the chunks it received.

Run this file: a page opens in your browser (report_lab1.html) with the dataset, and the answers to label.

YOUR LABELS
  For each of the 13 answers, decide two things, using the chunks and the reference answer (the page shows them):
    faithful   : every claim of the answer is stated in at least one of the chunks the application received
                 (even if another chunk disagrees, even if the chunk is wrong). Otherwise: unfaithful.
    correct    : the answer gives the key facts of the reference answer and does not contradict it. Otherwise: incorrect.
  Write one line per question in my_labels.txt, for example:   g01  faithful  incorrect
  Faithful is not the same as correct: an answer can be faithful to a wrong source. In lab 3 a judge model will label the
  same answers, and you will see where it disagrees with you. Run this file again when all the lines are written.
"""
from lab_tools import (
    get_corpus,
    labelling_cards,
    load_golden,
    logger,
    read_labels,
    report_dataset,
    show_report,
)

if __name__ == "__main__":
    items = load_golden()
    corpus = get_corpus()
    labels, problems = read_labels()
    body = report_dataset(items) + labelling_cards(corpus)
    if problems:
        show_report("lab1", "Lab 1: the golden dataset and the answers to label", body, "13 answers to label")
        for problem in problems[:5]:
            logger.info(problem)
        raise SystemExit("Labels not done yet: write your labels in my_labels.txt (see the page in your browser), then run this file again.")

    faithful = sum(1 for label in labels.values() if label[0])
    correct = sum(1 for label in labels.values() if label[1])
    logger.info(f"You labelled {len(labels)} answers: {faithful} faithful, {correct} correct.")
    incorrect_by_type = {}
    for item in items:
        if not labels[item["id"]][1]:
            incorrect_by_type[item["type"]] = incorrect_by_type.get(item["type"], 0) + 1
    logger.info(f"Incorrect answers by type of question: {incorrect_by_type}")
    show_report("lab1", "Lab 1: the golden dataset and the answers to label", body, f"labelled {len(labels)} answers: {faithful} faithful, {correct} correct")
